export const knowledgeService = {
  async getColorIssues(keyword: string = ''): Promise<QAItem[]> {
    try {
      const { data } = await api.get('/knowledge/color-issues', {
        params: { keyword },
      })
      return data.items || fallbackColorIssues
    } catch {
      if (!keyword) return fallbackColorIssues
      const kw = keyword.toLowerCase()
      return fallbackColorIssues.filter(
        (item) =>
          item.question.toLowerCase().includes(kw) ||
          item.answer.toLowerCase().includes(kw) ||
          item.tags?.some((t) => t.toLowerCase().includes(kw))
      )
    }
  },

  async getPhotoTips(): Promise<QAItem[]> {
    try {
      const { data } = await api.get('/knowledge/photo-tips')
      return data.items || fallbackPhotoTips
    } catch {
      return fallbackPhotoTips
    }
  },

  async getShops(city: string = 'all'): Promise<Shop[]> {
    try {
      const { data } = await api.get('/knowledge/shops', {
        params: { city },
      })
      return data.items || fallbackShops
    } catch {
      if (city === 'all') return fallbackShops
      return fallbackShops.filter((s) => s.city === city)
    }
  },

  async getBrands(category: string = 'all'): Promise<Brand[]> {
    try {
      const { data } = await api.get('/knowledge/brands', {
        params: { category },
      })
      return data.items || fallbackBrands
    } catch {
      if (category === '全部' || category === 'all') return fallbackBrands
      return fallbackBrands.filter((b) => b.category.includes(category))
    }
  },
}
